#!/usr/bin/env node
// ---------------------------------------------------------------------------------------------------------------------
// android-build/native/generate-data.mjs
//
// The native widgets must show the SAME "Ayah of the Day" as the app's home card, and the Bengali surah names. Both live in
// js/data.js (AYAH_OF_DAY_POOL, surahNamesBn). Instead of copying them by hand into Kotlin, this script reads them and writes
// kotlin/com/techverse/quranbangla/core/SurahData.kt. tests/native-overlay.test.js regenerates the file in memory and fails if
// the committed one is stale, so the two can never drift apart.
//
//   node android-build/native/generate-data.mjs          writes the file
//   node android-build/native/generate-data.mjs --check  exits 1 when the committed file is out of date
// ---------------------------------------------------------------------------------------------------------------------
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
export const OUTPUT = path.join(HERE, 'kotlin', 'com', 'techverse', 'quranbangla', 'core', 'SurahData.kt');

const ktString = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n') + '"';

export function extract(repo = REPO) {
  const data = fs.readFileSync(path.join(repo, 'js', 'data.js'), 'utf8');
  const names = /const surahNamesBn\s*=\s*\[([\s\S]*?)\];/.exec(data);
  const pool = /const AYAH_OF_DAY_POOL\s*=\s*\[([\s\S]*?)\];/.exec(data);
  if (!names || !pool) throw new Error('js/data.js: surahNamesBn or AYAH_OF_DAY_POOL not found');
  const bn = [...names[1].matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => JSON.parse('"' + m[1] + '"'));
  const picks = [...pool[1].matchAll(/\{\s*s\s*:\s*(\d+)\s*,\s*a\s*:\s*(\d+)\s*\}/g)].map((m) => [Number(m[1]), Number(m[2])]);
  const counts = JSON.parse('[' + /AYAH_COUNTS\s*=\s*\[([^\]]+)\]/.exec(fs.readFileSync(path.join(repo, 'app', 'js', 'data.js'), 'utf8'))[1] + ']');
  if (bn.length !== 114 || bn.some((n) => !n.trim())) throw new Error(`surahNamesBn must have 114 names, found ${bn.length}`);
  if (!picks.length) throw new Error('AYAH_OF_DAY_POOL is empty');
  for (const [s, a] of picks) if (s < 1 || s > 114 || a < 1 || a > counts[s - 1]) throw new Error(`AYAH_OF_DAY_POOL has an ayah that does not exist: ${s}:${a}`);
  return { bn, picks };
}

export function generate(repo = REPO) {
  const { bn, picks } = extract(repo);
  const names = bn.map((n) => '        ' + ktString(n)).join(',\n');
  const pairs = picks.map(([s, a]) => `        intArrayOf(${s}, ${a})`).join(',\n');
  return `package com.techverse.quranbangla.core

/**
 * GENERATED by android-build/native/generate-data.mjs from js/data.js - do not edit by hand.
 * (tests/native-overlay.test.js fails when this file is out of date.)
 */
object SurahData {
    /** Bengali surah names, index 0 = surah 1 (js/data.js surahNamesBn). */
    val NAMES_BN: Array<String> = arrayOf(
${names}
    )

    /** (surah, ayah) pairs of the "Ayah of the Day" pool (js/data.js AYAH_OF_DAY_POOL). */
    val AYAH_OF_DAY: Array<IntArray> = arrayOf(
${pairs}
    )
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const text = generate();
    if (process.argv.includes('--check')) {
      const have = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
      if (have !== text) { console.error('SurahData.kt is out of date - run: node android-build/native/generate-data.mjs'); process.exit(1); }
      console.log('SurahData.kt is up to date');
    } else {
      fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
      fs.writeFileSync(OUTPUT, text);
      console.log('written', path.relative(REPO, OUTPUT));
    }
  } catch (e) { console.error('ERROR: ' + e.message); process.exit(1); }
}
